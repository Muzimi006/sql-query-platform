package com.example.sqlquery.service.llm;

/**
 * 大模型客户端。
 *
 * <h2>为什么先抽一层接口</h2>
 *
 * <p>因为"接哪个模型"是本项目里<b>最可能变</b>的一件事：
 * 私有化部署、换供应商、换模型版本、本地 Ollama 调试……
 * 而业务侧真正需要的东西只有一句话：「给一段中文需求，还我一条 SQL」。
 *
 * <p>抽成接口之后：
 * <ul>
 *   <li>业务代码只依赖这个方法，换模型不改业务；</li>
 *   <li>测试里塞一个假的实现就能覆盖全部分支 —— 包括"模型胡说八道"这一类
 *       最难在真实模型上稳定复现的情况；</li>
 *   <li>没配密钥时提供一个"明确报错"的实现，而不是让应用起不来。</li>
 * </ul>
 *
 * <h2>⚠️ 这个接口的返回值是<b>不可信输入</b></h2>
 *
 * <p>实现方返回的字符串必须被当成<b>和用户手敲的 SQL 完全同等</b>的东西：
 * 它要经过同样的四道防线（解析/单语句 → 类型白名单 → AST 危险函数与系统库 → 字符串兜底），
 * 通过了也只是"能提交工单"，绝不等于"能执行"。
 *
 * <p><b>大模型的输出永远不能成为安全边界。</b>提示词里写的约束是效率优化
 * （让模型一次就写对），不是安全措施 —— 模型完全可以无视它，
 * 而我们必须假设它一定会无视。
 */
public interface LlmClient {

    /**
     * 根据系统提示（含方言、表结构、硬性规则）和用户需求生成 SQL。
     *
     * @return 模型返回的原始文本，调用方负责剥代码围栏、判断哨兵值并做安全校验
     */
    String generateSql(String systemPrompt, String userPrompt);

    /** 这个功能当前是否可用。前端据此决定要不要显示入口。 */
    boolean available();
}
